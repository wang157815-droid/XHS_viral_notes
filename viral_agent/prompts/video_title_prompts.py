def get_title_classification_prompt(title: str) -> str:
    """
    获取标题分类提示词

    Args:
        title: 视频标题

    Returns:
        完整的提示词
    """
    return f"{VIDEO_TITLE_ANALYSIS_PROMPT}\n\n待分析标题：{title}"


def parse_title_classification(result: str) -> dict:
    """
    解析标题分类结果

    Args:
        result: AI返回的分类结果

    Returns:
        结构化的分类信息
    """
    try:
        # 清理结果字符串
        result = result.strip() if result else ''

        # 处理空响应或无效响应
        if not result or result == 'N/A' or result.startswith('分析失败') or result.startswith('API'):
            return {
                'main_category': '',  # 空字符串表示需要回退到规则分类
                'sub_category': '',
                'raw_result': result,
                'needs_fallback': True  # 标记需要回退
            }

        # 解析分类格式：主分类-子分类
        parts = result.split('-')

        if len(parts) >= 2:
            main_cat = parts[0].strip()
            sub_cat = '-'.join(parts[1:]).strip()

            # 验证主分类不为空
            if not main_cat:
                return {
                    'main_category': '',
                    'sub_category': sub_cat or '',
                    'raw_result': result,
                    'needs_fallback': True
                }

            return {
                'main_category': main_cat,
                'sub_category': sub_cat,
                'raw_result': result
            }
        else:
            # 单个词的情况，作为主分类
            if result:
                return {
                    'main_category': result,
                    'sub_category': '待细分',
                    'raw_result': result
                }
            else:
                return {
                    'main_category': '',
                    'sub_category': '',
                    'raw_result': result,
                    'needs_fallback': True
                }
    except Exception as e:
        return {
            'main_category': '',
            'sub_category': '',
            'error': str(e),
            'raw_result': str(result) if result else '',
            'needs_fallback': True
        }


